package dev.spw.folia

import com.xuncorp.spw.workshop.api.PluginPermission
import com.xuncorp.spw.workshop.api.PlaybackExtensionPoint
import com.xuncorp.spw.workshop.api.PlaybackExtensionPoint.LyricsLine
import com.xuncorp.spw.workshop.api.PlaybackExtensionPoint.MediaItem
import com.xuncorp.spw.workshop.api.PlaybackExtensionPoint.State
import com.xuncorp.spw.workshop.api.UnstableSpwWorkshopApi
import com.xuncorp.spw.workshop.api.WorkshopApi
import org.pf4j.Extension
import java.util.Base64
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.Executors
import java.util.concurrent.ScheduledExecutorService
import java.util.concurrent.TimeUnit
import java.util.concurrent.atomic.AtomicBoolean
import java.util.concurrent.atomic.AtomicLong
import java.util.concurrent.atomic.AtomicReference

/**
 * Playback bridge between SPW and the Folia helper window.
 *
 * PF4J instantiates this class because of the [Extension] annotation (the plugin jar must carry
 * `META-INF/extensions.idx`, generated by the PF4J annotation processor wired via kapt). The plugin
 * instance finds it through [get] and asks it for protocol snapshots.
 *
 * Position: the Workshop API only pushes `onPositionUpdated` at ~1 Hz. All callbacks feed
 * [TimelineController] (poc/audio drop-in, measured 2.95 ms mean error on a 1 Hz feed) which
 * interpolates with a monotonic clock, handles pause/seek/rate/buffering/track changes, and exposes
 * a smooth position for the 100 ms state pump.
 */
@Extension
class FoliaPlaybackExtension : PlaybackExtensionPoint {

    private val controller = TimelineController()

    @Volatile private var mediaItem: MediaItem? = null
    @Volatile private var coverDataUrl: String? = null
    @Volatile private var lyrics: List<LyricsLine> = emptyList()

    private val lyricsVersion = AtomicLong(0)
    private val trackVersion = AtomicLong(0)
    private val lastTrackRefreshMs = AtomicLong(0)
    private val refreshing = AtomicBoolean(false)

    /** Id of the track whose cover is currently being fetched (dedupes out-of-band requests). */
    private val coverLoadingId = AtomicReference<String?>(null)
    private val trackExecutor: ScheduledExecutorService = Executors.newSingleThreadScheduledExecutor { r ->
        Thread(r, "spw-folia-track").apply { isDaemon = true }
    }

    private val cachedLyrics = AtomicReference<String?>(null)
    private val cachedLyricsVersion = AtomicLong(-1)
    private val cachedTrack = AtomicReference<String?>(null)
    private val cachedTrackVersion = AtomicLong(-1)

    // ---- diagnostic counters: first call + one summary per 10 s -------------------------------
    private val callbackCounts = ConcurrentHashMap<String, AtomicLong>()
    private val lastSummaryMs = AtomicLong(0L)

    private fun noteCallback(kind: String, detail: Any?) {
        val count = callbackCounts.computeIfAbsent(kind) { AtomicLong(0) }.incrementAndGet()
        if (count == 1L) {
            FoliaPlugin.logStatic("callback $kind first: $detail")
        }
        val now = System.currentTimeMillis()
        val last = lastSummaryMs.get()
        if (now - last >= 10_000L && lastSummaryMs.compareAndSet(last, now)) {
            val summary = callbackCounts.entries.joinToString(", ") { "${it.key}=${it.value.get()}" }
            val snapshot = controller.snapshot()
            FoliaPlugin.logStatic(
                "callbacks/10s: $summary | pos=${controller.positionMs().toLong()} " +
                    "playing=${snapshot.playing} duration=${snapshot.durationMs}"
            )
        }
    }

    init {
        instance = this
        FoliaPlugin.logStatic("extension instance created (${this::class.java.name})")
    }

    // ------------------------------------------------------------- protocol ----

    fun snapshot(): PlaybackSnapshot {
        val timelineSnapshot = controller.snapshot()
        val position = controller.positionMs()
        return PlaybackSnapshot(
            posMs = position.toLong().coerceAtLeast(0L),
            durationMs = mediaItem?.duration ?: timelineSnapshot.durationMs,
            playing = timelineSnapshot.playing,
            rate = timelineSnapshot.rate
        )
    }

    fun lyricsJson(): String? {
        val version = lyricsVersion.get()
        if (cachedLyricsVersion.get() == version) return cachedLyrics.get()
        val lines = lyrics
        if (lines.isEmpty()) {
            val empty = "[]"
            cachedLyrics.set(empty)
            cachedLyricsVersion.set(version)
            return empty
        }
        val sb = StringBuilder(lines.size * 96 + 32)
        sb.append('[')
        lines.forEachIndexed { index, line ->
            if (index > 0) sb.append(',')
            sb.append("{\"startMs\":").append(line.startTime)
                .append(",\"endMs\":").append(line.endTime)
                .append(",\"main\":").append(Json.str(line.pureMainText))
                .append(",\"sub\":").append(Json.str(line.pureSubText ?: ""))
                .append(",\"cells\":[")
            line.lyricsCells.forEachIndexed { cellIndex, cell ->
                if (cellIndex > 0) sb.append(',')
                sb.append("{\"startMs\":").append(cell.startTime)
                    .append(",\"endMs\":").append(cell.endTime)
                    .append(",\"text\":").append(Json.str(cell.text))
                    .append('}')
            }
            sb.append("]}")
        }
        sb.append(']')
        val json = sb.toString()
        cachedLyrics.set(json)
        cachedLyricsVersion.set(version)
        return json
    }

    fun trackJson(): String? {
        refreshTrackIfStale()
        val version = trackVersion.get()
        if (cachedTrackVersion.get() == version) return cachedTrack.get()
        val item = mediaItem ?: run {
            cachedTrack.set(null)
            cachedTrackVersion.set(version)
            return null
        }
        val json = buildString {
            append("{\"id\":").append(Json.str(item.id))
            append(",\"title\":").append(Json.str(item.title))
            append(",\"artist\":").append(Json.str(item.artist))
            append(",\"album\":").append(Json.str(item.album))
            append(",\"durationMs\":").append(item.duration)
            coverDataUrl?.let { append(",\"coverDataUrl\":").append(Json.str(it)) }
            append('}')
        }
        cachedTrack.set(json)
        cachedTrackVersion.set(version)
        return json
    }

    // ------------------------------------------------------------ extension ----

    private fun mapState(state: State): PlaybackState = when (state) {
        State.Idle -> PlaybackState.IDLE
        State.Buffering -> PlaybackState.BUFFERING
        State.Ready -> PlaybackState.READY
        State.Ended -> PlaybackState.ENDED
    }

    override fun onStateChanged(state: State) {
        controller.onStateChanged(mapState(state))
        noteCallback("state", state.name)
    }

    override fun onIsPlayingChanged(isPlaying: Boolean) {
        controller.onIsPlayingChanged(isPlaying)
        noteCallback("playing", isPlaying)
    }

    override fun onSeekTo(position: Long) {
        controller.onSeekTo(position)
        noteCallback("seek", position)
    }

    override fun onPositionUpdated(position: Long) {
        controller.onPositionUpdated(position)
        noteCallback("position", position)
    }

    override fun onLyricsLinesUpdated(lyricsLines: List<LyricsLine>) {
        lyrics = lyricsLines
        lyricsVersion.incrementAndGet()
        noteCallback("lyrics", lyricsLines.size)
    }

    override fun onLyricsLineUpdated(lyricsLine: LyricsLine?) {
        // Full timeline delivery (onLyricsLinesUpdated) is what we render; nothing to do here.
    }

    override fun onBeforeLoadLyrics(mediaItem: MediaItem): String? {
        adoptMediaItem(mediaItem)
        refreshTrackIfStale(force = true)
        noteCallback("beforeLoadLyrics", mediaItem.title)
        return null
    }

    override fun onAfterLoadLyrics(mediaItem: MediaItem): String? {
        adoptMediaItem(mediaItem)
        refreshTrackIfStale(force = true)
        noteCallback("afterLoadLyrics", mediaItem.title)
        return null
    }

    // ---------------------------------------------------------------- track ----

    private fun adoptMediaItem(item: MediaItem) {
        val previous = mediaItem
        mediaItem = item
        if (previous == null || previous.id != item.id || previous.title != item.title) {
            coverDataUrl = null
            trackVersion.incrementAndGet()
            controller.onTrackChanged(item.duration, controller.positionMs().toLong())
            // Fetch the cover immediately: the pump only pushes a track whose JSON changed, and the
            // cover is what makes the page derive the new palette (v0.1.8 — auto-advance lag).
            requestCoverLoad(item)
        } else {
            controller.onDurationChanged(item.duration)
        }
    }

    /**
     * Loads the cover for [item] on the track executor (deduped per track id), so switching songs
     * does not depend on the next throttled poll before the theme can follow the new cover.
     */
    private fun requestCoverLoad(item: MediaItem) {
        if (item.id.isEmpty() || coverDataUrl != null) return
        if (!coverLoadingId.compareAndSet(null, item.id)) return
        trackExecutor.execute {
            try {
                if (coverDataUrl == null && mediaItem?.id == item.id) loadCover(item)
            } catch (t: Throwable) {
                FoliaPlugin.logStatic("cover load failed: ${t::class.java.name}: ${t.message}")
            } finally {
                coverLoadingId.compareAndSet(item.id, null)
            }
        }
    }

    private fun refreshTrackIfStale(force: Boolean = false) {
        val now = System.currentTimeMillis()
        // 400 ms (was 1.5 s): a song switch is noticed by the poll within ~0.4 s even when SPW does
        // not fire a lyrics callback for it, which is the other half of the v0.1.8 auto-advance fix.
        if (!force && now - lastTrackRefreshMs.get() < 400L) return
        if (!refreshing.compareAndSet(false, true)) return
        lastTrackRefreshMs.set(now)
        trackExecutor.execute {
            try {
                if (!isLibraryReadGranted()) return@execute
                val item = WorkshopApi.playback.getCurrentMediaItem() ?: return@execute
                if (item != mediaItem) {
                    adoptMediaItem(item)
                }
                if (coverDataUrl == null) {
                    requestCoverLoad(item)
                }
            } catch (t: Throwable) {
                FoliaPlugin.logStatic("track refresh error: ${t::class.java.name}: ${t.message}")
            } finally {
                refreshing.set(false)
            }
        }
    }

    private fun loadCover(item: MediaItem) {
        try {
            val fetched = WorkshopApi.library.getCoverById(item.id).toCompletableFuture().get(2, TimeUnit.SECONDS)
            if (fetched == null || fetched.isEmpty()) return
            val (bytes, mime) = shrinkCover(fetched)
            coverDataUrl = "data:$mime;base64," + Base64.getEncoder().encodeToString(bytes)
            trackVersion.incrementAndGet()
            FoliaPlugin.logStatic("cover ready id=${item.id} ${fetched.size} -> ${bytes.size} bytes ($mime)")
        } catch (t: Throwable) {
            FoliaPlugin.logStatic("cover load failed: ${t::class.java.name}: ${t.message}")
        }
    }

    /**
     * SPW hands over the artwork at full resolution — 6 MB PNG/JPEG covers are common, which turns
     * every song switch into a multi-megabyte base64 string on the protocol pipe and a slow decode
     * in the page before the palette can follow (v0.1.8: that lag was one half of the auto-advance
     * report). The page only samples a 48×48 canvas for the theme, so a 512 px JPEG is plenty.
     */
    private fun shrinkCover(raw: ByteArray): Pair<ByteArray, String> {
        if (raw.size <= COVER_SHRINK_THRESHOLD) return raw to sniffImageMime(raw)
        return try {
            val source = javax.imageio.ImageIO.read(java.io.ByteArrayInputStream(raw))
                ?: return raw to sniffImageMime(raw)
            val longest = maxOf(source.width, source.height)
            if (longest <= COVER_MAX_EDGE) return raw to sniffImageMime(raw)
            val scale = COVER_MAX_EDGE.toDouble() / longest
            val width = maxOf(1, (source.width * scale).toInt())
            val height = maxOf(1, (source.height * scale).toInt())
            val target = java.awt.image.BufferedImage(width, height, java.awt.image.BufferedImage.TYPE_INT_RGB)
            val graphics = target.createGraphics()
            try {
                graphics.setRenderingHint(
                    java.awt.RenderingHints.KEY_INTERPOLATION,
                    java.awt.RenderingHints.VALUE_INTERPOLATION_BILINEAR
                )
                graphics.drawImage(source, 0, 0, width, height, null)
            } finally {
                graphics.dispose()
            }
            val out = java.io.ByteArrayOutputStream()
            javax.imageio.ImageIO.write(target, "jpg", out)
            out.toByteArray() to "image/jpeg"
        } catch (t: Throwable) {
            FoliaPlugin.logStatic("cover shrink skipped: ${t::class.java.name}: ${t.message}")
            raw to sniffImageMime(raw)
        }
    }

    private fun sniffImageMime(bytes: ByteArray): String = when {
        bytes.size >= 3 && bytes[0] == 0xFF.toByte() && bytes[1] == 0xD8.toByte() -> "image/jpeg"
        bytes.size >= 8 && bytes[0] == 0x89.toByte() && bytes[1] == 0x50.toByte() -> "image/png"
        bytes.size >= 4 && bytes[0] == 0x47.toByte() && bytes[1] == 0x49.toByte() -> "image/gif"
        bytes.size >= 12 && bytes[0] == 0x52.toByte() && bytes[1] == 0x49.toByte() -> "image/webp"
        else -> "image/jpeg"
    }

    private fun isLibraryReadGranted(): Boolean = try {
        WorkshopApi.manager.isPermissionGranted(PluginPermission.LIBRARY_READ)
    } catch (t: Throwable) {
        false
    }

    fun shutdown() {
        trackExecutor.shutdownNow()
    }

    companion object {
        /** Covers above this size are re-encoded to a small JPEG before they hit the pipe. */
        private const val COVER_SHRINK_THRESHOLD = 160_000
        private const val COVER_MAX_EDGE = 512
        @Volatile
        private var instance: FoliaPlaybackExtension? = null

        fun get(): FoliaPlaybackExtension? = instance
    }
}

/** Immutable state line snapshot handed to the helper. */
class PlaybackSnapshot(
    val posMs: Long,
    val durationMs: Long,
    val playing: Boolean,
    val rate: Double
)
